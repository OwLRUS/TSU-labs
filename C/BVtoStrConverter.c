/*
Функция inversion выполняет инверсию булева вектора
unsigned char* vec - булев вектор
size_t bits - размер булева вектора без учета "хвоста"
*/
void inversion(unsigned char* vec, size_t bits)
{
    if (vec && bits > 0) // Проверка входящего значения
    {
        size_t bytes = (bits - 1) / 8 + 1; // Высчитываем количество байт вектора для органицации цикла
        unsigned char tab = 0;
        int tail = 0;
        if (bits % 8 != 0) tail = 8 - bits % 8; // Вычисляем размер хвоста 
        if (tail > 0) // Если хвост существует, то нужно подготовить маску, которая обнулит значения в хвосте
        {
            unsigned char mask = 1;
            mask = mask << 7;
            for (int i = 0; i < tail; i++) // Заполняем маску tab единицы в ячейки хвоста
            {
                tab = tab | mask;
                mask = 1;
                mask = mask << (6 - i);
            }
            tab = ~tab; // Инвертируем маску, чтобы в ячейках хвоста были нули, а в остальных единицы
        }
        for (int i = 0; i < bytes; i++) // Инвертируем сам булев вектор
        {
            vec[i] = ~vec[i];
        }
        if (tail > 0) vec[bytes - 1] = vec[bytes - 1] & tab; // Если все таки хвост был, то последнюю ячейку умножаем на маску, тем самым обнуляем хвост
    }
}
/*
Функция shiftLeft выполняет сдвиг булева вектора на К разрядов влево
unsigned char* vec - булев вектор
size_t bits - размер булева вектора без учета "хвоста"
int k - количество разрядов, на которые нужно сдвинуть вектор
*/
void shiftLeft(unsigned char* vec, size_t bits, int k)
{
    if (vec && bits > 0) // Проверка входящего значения
    {
        if (k >= bits) // Проверяем случай, когда пользователь пожелает сдвинуть вектор на его размер (или больше)
        {
            for (int i = 0; i < (bits - 1) / 8 + 1; i++) // Тогда вектор обнулится
            {
                vec[i] = 0;
            }
        }
        else
        {
            int tail = 0;
            if (bits % 8 != 0) tail = 8 - bits % 8; // Вычисляем размер хвоста
            unsigned char maskVec_i = 0, maskVec_j = 0;
            int i, j, xk = 8;
            for (j = (k - 1) / 8; j >= 0; j--) // Цикл определит сколько целых байт нужно сместить, чтобы в конце сместить оставшиеся биты
            // Цикл является реализацией сдвига для любого К и любого размера булева вектора
            {
                if (j == 0) xk = (k - 1) % 8 + 1; // Если мы выполнили все целые сдвиги (на 8), то вычисляем на сколько остается сдвинуть вектор
                for (i = (bits - 1) / 8; i >= 0; i--) // Начинаем сдвиг с последнего байта
                {
                    if (i == (bits - 1) / 8) // Реализация сдвига для последнего байта отличается от остальных
                    {
                        if (xk != 8) // Если мы сдвигаем не на целый байт, то реализуем по особому
                        {
                            maskVec_i = vec[i]; // Запоминаем байт вектора в маску
                            if ((8 - xk - tail) > 0) maskVec_i = maskVec_i >> (8 - xk - tail); /* Сдвигаем маску так, чтобы запомнить разряды,
                            которые уйдут после сдвига с учетом хвоста, и чтобы сразу прибавить эти разряды в следующий байт */
                            else maskVec_i = maskVec_i << (xk + tail - 8);
                            vec[i] = vec[i] << xk; // Сдвигаем байт
                            vec[i] = vec[i] << tail; // Обнуляем хвост
                            vec[i] = vec[i] >> tail;
                        }
                        else // Если сдвигаем на байт, то запоминаем байт вектора без хвоста и обнуляем байт
                        {
                            maskVec_i = vec[i] << tail;
                            vec[i] = 0;
                        }
                    }
                    else // Для всех байтов, кроме последнего, алгорим один и тот же
                    {
                        if (xk != 8) // Если сдвигаем не на байт
                        {
                            maskVec_j = maskVec_i; // Запоминаем, что пришло с прошлого байта
                            maskVec_i = vec[i]; // Сразу вычисляем, что уйдет в следующий байт
                            maskVec_i = maskVec_i >> (8 - xk); // И сдвигаем так, чтобы можно было без вычислений добавить его в следующий байт
                            vec[i] = vec[i] << xk; // Сдвигаем байт вектора
                            vec[i] = vec[i] | maskVec_j; // Прибавляем разряды, которые пришли с прошлого байта
                        }
                        else // Если сдвиг оказался на 8, то запоминаем целый байт вектора и вместо него пишем то, что пришло с прошлого байта 
                        {
                            maskVec_j = maskVec_i;
                            maskVec_i = vec[i];
                            vec[i] = maskVec_j;
                        }
                    }
                }
            }
        }
    }
}
/*
Функция shiftRight выполняет сдвиг булева вектора на К разрядов вправо
unsigned char* vec - булев вектор
size_t bits - размер булева вектора без учета "хвоста"
int k - количество разрядов, на которые нужно сдвинуть вектор
*/
void shiftRight(unsigned char* vec, size_t bits, int k)
{
    if (vec && bits > 0) // Проверка входящего значения
    {
        if (k >= bits) // Проверяем случай, когда пользователь пожелает сдвинуть вектор на его размер (или больше)
        {
            for (int i = 0; i < (bits - 1) / 8 + 1; i++) // Тогда вектор обнулится
            {
                vec[i] = 0;
            }
        }
        else
        {
            int tail = 0;
            if (bits % 8 != 0) tail = 8 - bits % 8; // Вычисляем размер хвоста
            unsigned char maskVec_i, maskVec_j;
            int i, j, xk = 8;
            for (j = (k - 1) / 8; j >= 0; j--) // Цикл определит сколько целых байт нужно сместить, чтобы в конце сместить оставшиеся биты
            // Цикл является реализацией сдвига для любого К и любого размера булева вектора
            {
                if (j == 0) xk = (k - 1) % 8 + 1; // Если мы выполнили все целые сдвиги (на 8), то вычисляем на сколько остается сдвинуть вектор
                for (i = 0; i < (bits - 1) / 8 + 1; i++) // Начинаем сдвиг с первого байта
                {
                    if (i == 0) // Для первого первого байта алгоритм отличается
                    {
                        if (xk != 8) // Если сдвиг меньше чем на 8
                        {
                            maskVec_i = vec[i]; // Запоминаем байт вектора
                            maskVec_i = maskVec_i << (8 - xk); // Сдвигаем для удобства сложения
                            vec[i] = vec[i] >> xk; // Сдвигаем сам байт
                        }
                        else // Если сдвиг на 8
                        {
                            maskVec_i = vec[i]; // Запоминаем байт и обнуляем его
                            vec[i] = 0;
                        }
                    }
                    else // Для всех байт, кроме первого и последнего, алгоритм один и тот же
                    {
                        if (xk != 8)
                        {
                            if (i != (bits - 1) / 8) // Разделяю алгоритм для последнего байта и центральных
                            {
                                maskVec_j = maskVec_i; // Запоминаем, что пришло с прошлого байта
                                maskVec_i = vec[i]; // Сразу вычисляем, что уйдет в следующий байт
                                maskVec_i = maskVec_i << (8 - xk); // И сдвигаем так, чтобы можно было без вычислений добавить его в следующий байт
                                vec[i] = vec[i] >> xk; // Сдвигаем байт вектора
                                vec[i] = vec[i] | maskVec_j; // Прибавляем разряды, которые пришли с прошлого байта
                            }
                            else // Последний байт
                            {
                                maskVec_j = maskVec_i >> tail; // Обнуляем хвост
                                vec[i] = vec[i] >> xk; // Сдвигаем байт
                                vec[i] = vec[i] | maskVec_j; // Прибавляем разряды, которые пришли с прошлого байта
                            }
                        }
                        else // Сдвиг на 8
                        {
                            if (i != (bits - 1) / 8) // Разделяю алгоритм для последнего байта и центральных
                            {
                                maskVec_j = maskVec_i; // Запоминаем, что пришло с прошлого байта
                                maskVec_i = vec[i]; // Записываем целый байт вектора
                                vec[i] = maskVec_j; // Вписываем, что пришло с прошлого байта
                            }
                            else // Последний байт
                            {
                                maskVec_j = maskVec_i >> tail; // Сдвигаем учитывая размер хвоста
                                vec[i] = maskVec_j; // Вписываем, что пришло с прошлого байта
                            }
                        }
                    }
                }
            }
        }
    }
}
