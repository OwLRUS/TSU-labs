/*
Функция convertStrToLongBv выполняет конвертацию строки в булев вектор
char *str - строка, представляющая собой массив символов 
int *cells - количество байт, требуемых для создания булева вектора
Выходящее значение - требуемый булев вектор или NULL, если был некорректно создан динамический массив для буделва вектора или
входящее значение было равно NULL 
*/
unsigned char* convertStrToLongBvV2(char* str, int* cells)
{
    if (str && cells) // Проверка входящих значений
    {
        int len = 0, i = 0, ix = 0, a = 0;
        unsigned char mask = 1;
        len = strlen(str); // Вычисляем длину входящей строки (количество бит) 
        *cells = ((len - 1) / 8) + 1; // Вычисляем и сохраняем количество байт булева вектора 
        unsigned char* vec = (unsigned char*)malloc((*cells) * sizeof(unsigned char));
        if (vec) // Проверка на успешное создание динамического массива
        {
            for (int i = 0; i < *cells; i++) vec[i] = 0; // Заполняем созданный массив нулями 
            for (int i = 0; i < *cells; i++) // Теперь с помощью маски заполняем массив значениями
            {
                mask = 1;
                for (int j = 0; j < 8 && (ix < len); j++)
                {
                    if (str[ix] != '0') // Если элемент входящей строки равен нулю, то в булевом векторе оставим ноль, иначе добавим единицу
                    {
                        vec[i] = vec[i] | mask;
                    }
                    mask = mask << 1;
                    ix++;
                }
            }
            return vec;
        }
    }
    return NULL;
}

