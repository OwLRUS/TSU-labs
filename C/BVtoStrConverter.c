/*
Функция set_bit_1 устанавливает единицу в К-ый разряд булева вектора
unsigned char* vec - булев вектор
size_t len - длина вектора без "хвоста"
size_t k - номер разряда, в который нужно установить единицу
*/
void set_bit_1(unsigned char* vec, size_t len, size_t k)
{
    if (vec) // Проверка входящего значения
    {
        if(k < len) // Проверка не выходит ли К за рамки размера вектора
        {
            int byte = 0, pos = 0, bit = 0, cells = (len - 1)/8 + 1, tail = cells*8 - len;
            unsigned char mask = 1;
            byte = k / 8; // Вычисляем номер байта булева вектора, в котором находится К-ый разряд
            bit = k % 8; // Вычисляем его порядок в этом байте
            if(tail > 0 && byte == cells - 1)
            {
                mask = mask << (7 - bit - tail); // Сдвигаем маску так, чтобы единица стояла на месте К-ого разряда в байте 
                vec[byte] = vec[byte] | mask; // Прибавляем эту единицу в вектор
            }
            else
            {
                mask = mask << (7 - bit); // Сдвигаем маску так, чтобы единица стояла на месте К-ого разряда в байте 
                vec[byte] = vec[byte] | mask; // Прибавляем эту единицу в вектор
            }
        }
    }
}
