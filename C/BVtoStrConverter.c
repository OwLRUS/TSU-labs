/*
Функция logMul выполняет логическое умножение двух булевых векторов
unsigned char* vecA - булев вектор (первый множитель)
unsigned char* vecB - булев вектор (второй множитель)
size_t szA - размер первого вектора без "хвоста"
size_t szB - размер второго вектора без "хвоста"
Выходящее значение - булев вектор, который является результатом логического умножения
*/
unsigned char* logMul(unsigned char* vecA, size_t szA, unsigned char* vecB, size_t szB)
{
    unsigned char* str = NULL;
    if (vecA && vecB) // Проверка входящих значений
    {
        size_t bytesA = (szA - 1) / 8 + 1; // Вычисляем количество байт каждого вектора
        size_t bytesB = (szB - 1) / 8 + 1;
        int ix;
        if (szA > szB) ix = szA; // Находим какой из векторов больше, чтобы создать новый вектор по размеру наибольшего
        else ix = szB;
        str = (unsigned char*)malloc(ix * sizeof(unsigned char));
        if (str) // Проверка успешного создания динамического массива 
        {
            for (int i = 0; i < ix; i++) // С помощью цикла выполняем логическое умножение для соответствующих байт векторов
            {
                str[i] = vecA[i] & vecB[i];
            }
        }
    }
    return str;
}
